/*
 * Config.h
 *
 * 定数・設定値の一元管理
 * Magic Numberを排除し、全ての定数を名前付きで管理
 */

#ifndef CONFIG_H
#define CONFIG_H

// ============================================================================
// 動作モード設定
// ============================================================================
// モード定義:
//   0: MODE_DEBUG      - デバッグ専用（PWMなし、シリアルあり）
//   1: MODE_PRODUCTION - 本番走行（PWMあり、シリアルなし）
//   2: MODE_DEBUG_RUN  - デバッグ走行（PWMあり、シリアルあり）
#define MODE_DEBUG 0
#define MODE_PRODUCTION 1
#define MODE_DEBUG_RUN 2

#define RUN_MODE MODE_PRODUCTION // ← ここで動作モードを選択

// 各機能の有効/無効を自動設定
#define ENABLE_SERIAL (RUN_MODE == MODE_DEBUG || RUN_MODE == MODE_DEBUG_RUN)
#define ENABLE_PWM (RUN_MODE == MODE_PRODUCTION || RUN_MODE == MODE_DEBUG_RUN)

// ============================================================================
// Bluetooth設定（HC-06モジュール）
// ============================================================================
// ログ出力: true でBluetooth経由のシリアル出力を有効化
#define ENABLE_BLUETOOTH_LOGGING false

// 緊急停止: true でBluetooth経由の緊急停止機能を有効化
#define ENABLE_BLUETOOTH_EMERGENCY true

const unsigned long BLUETOOTH_BAUD = 9600;  // HC-06のデフォルト速度

// ============================================================================
// ハードウェア設定
// ============================================================================
// TCA9548A I2Cマルチプレクサ
const uint8_t TCA9548A_ADDR = 0x70;

// センサー設定
const uint8_t NUM_SENSORS = 7;
const uint8_t SENSOR_CHANNELS[NUM_SENSORS] = {0, 1, 2, 3, 4, 5, 6};
const float SENSOR_ANGLES[NUM_SENSORS] = {-60.0, -40.0, -20.0, 0.0, 20.0, 40.0, 60.0};
const uint8_t FRONT_SENSOR_INDEX = 3;  // 正面センサーのインデックス（0度）

// PWM出力ピン
const uint8_t SERVO_PIN = 9;  // ステアリングサーボ
const uint8_t ESC_PIN = 10;   // ESC（モーター制御）

// ============================================================================
// センサーパラメータ
// ============================================================================
const uint16_t MIN_VALID_DISTANCE = 50;  // 最小有効測定距離（mm）
const uint16_t RELIABLE_RANGE = 4000;    // 信頼できる測定範囲（mm）L1Xは最大4m
// VL53L1X タイミング設定
const uint32_t L1X_TIMING_BUDGET_US = 33000;   // 測定時間（μs）50ms
const uint32_t L1X_INTER_MEASUREMENT_MS = 40;  // 測定間隔（ms）

// ============================================================================
// タイミング設定
// 40が最低値で秒間当たりの測定回数を最大化可能. 
// 40 ~ 60がセンサーのMediumモードの範囲で, 有効測定距離は~3m程度になる
// ============================================================================
const unsigned long MEASUREMENT_INTERVAL = 40;  // 60ms（L1X測定間隔以上を推奨）

// ============================================================================
// ステアリングパラメータ
// ============================================================================
const float MAX_STEERING_ANGLE = 30.0;  // 最大操舵角（度）

// ============================================================================
// ギャップ検出パラメータ
// ============================================================================
const float FARTHEST_HYSTERESIS = 100.0;  // 最遠センサー切り替えのヒステリシス（mm）

// ============================================================================
// 直進モードパラメータ
// 条件1: 前方センサーが十分開けている
// 条件2: 全センサーが壁から離れている AND 前方もある程度開けている
// どちらかを満たせば直進モード
// ============================================================================
const uint16_t STRAIGHT_THRESHOLD_FRONT = 3000;      // 条件1: 前方センサー閾値（mm）
const uint16_t STRAIGHT_THRESHOLD_MIN = 800;         // 条件2: 全センサー最小距離閾値（mm）
const uint16_t STRAIGHT_THRESHOLD_FRONT_MIN = 1500;  // 条件2: 前方センサー最低閾値（mm）

// ============================================================================
// PD制御パラメータ
/*
 推奨組み合わせ
  ┌────────────┬─────┬─────┬──────────────────────────┐
  │    目的    │ KP  │ KD  │           特徴           │
  ├────────────┼─────┼─────┼──────────────────────────┤
  │ 現状維持   │ 1.0 │ 0.0 │ 俊敏だが蛇行しやすい     │
  ├────────────┼─────┼─────┼──────────────────────────┤
  │ 軽い安定化 │ 1.0 │ 0.1 │ 反応維持、急変動のみ抑制 │
  ├────────────┼─────┼─────┼──────────────────────────┤
  │ バランス型 │ 0.9 │ 0.1 │ 全体的にやや抑え、安定   │
  ├────────────┼─────┼─────┼──────────────────────────┤
  │ 安定重視   │ 0.8 │ 0.2 │ マイルド、蛇行しにくい   │
  ├────────────┼─────┼─────┼──────────────────────────┤
  │ 高速向け   │ 0.7 │ 0.2 │ 最も安定、コーナー弱め   │
  └────────────┴─────┴─────┴──────────────────────────┘
  蛇行対策の第一歩: KP=1.0, KD=0.1 を試し、まだ蛇行するならKD=0.2へ。それでもダメならKPを0.9に下げる、という段階的アプローチが良いと思います。
*/
// ============================================================================
const float STEERING_KP = 1.0;  // 比例ゲイン
const float STEERING_KD = 0.1;  // 微分ゲイン（予測制御用、控えめからスタート）

// ============================================================================
// 安全パラメータ
// ============================================================================
const uint16_t EMERGENCY_FRONT_THRESHOLD = 400;  // 前方緊急閾値（mm）

// ============================================================================
// サーボ・ESC パルス幅設定
// ============================================================================
// サーボ（ステアリング）- 新サーボ: 1200(右)〜1500(中央)〜1800(左)
const uint16_t SERVO_CENTER = 1425;  // 中央位置（μs）
const uint16_t SERVO_MIN = 1125;     // 最小パルス幅（μs）= 最も右
const uint16_t SERVO_MAX = 1725;     // 最大パルス幅（μs）= 最も左

// ESC（速度制御）- 全てμs単位で統一
const uint16_t ESC_STOP_US = 1500;   // 停止（μs）
const uint16_t ESC_MIN_US = 1000;    // ESC最小パルス（μs）
const uint16_t ESC_MAX_US = 2000;    // ESC最大パルス（μs）

// ============================================================================
// 距離連動速度制御パラメータ
// ============================================================================
const bool SPEED_DISTANCE_LINK_ENABLED = false;  // true: 有効, false: 固定速度
const uint16_t DECEL_START_DISTANCE = 2000;     // 減速開始距離（mm）
const float DECEL_CURVE_EXPONENT = 0.5;         // 減速カーブ指数（0.2〜1.0、小さいほど急）
const uint16_t MAX_SPEED_US = 1640;             // 最高速度パルス（μs）
const uint16_t MIN_SPEED_US = 1580;             // 最低速度パルス（μs）

#endif  // CONFIG_H
